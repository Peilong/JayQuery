#!/usr/bin/env python3
"""Find grid cells that produced no result, and write a backfill sweep for them.

A trial that dies mid-training leaves a wandb run marked *finished* with no
``val/auc_best`` and no ``experiments/checkpoints/<id>/meta.json``, so a sweep
can look complete while cells are missing. This script treats the presence of
a meta.json as the only evidence a cell landed, since that file is what the
exhibits are built from.

The emitted config uses the ``cell`` axis (see
:func:`utils.wandb_utils.expand_cell`), which expresses an arbitrary scattered
set of cells as a single sweep.

Note: cells are credited on (placement, epsilon, seed) and not on
``embedding-dim``, so a width sweep sharing a placement and epsilon with the
placement grid is counted against it. Check the dimension separately when both
are in play.

Usage:
    python scripts/grid_holes.py --sweeps <id> [<id> ...]
    python scripts/grid_holes.py --sweeps <id> --out fill.yaml
"""

from __future__ import annotations

import argparse
import glob
import os
from pathlib import Path

#: The placement grid's intended axes. Kept here, not read from the sweep, so a
#: hole in a cell that was never dispatched at all is still reported.
PLACEMENTS = ("server", "cut-layer", "label", "all")
EPSILONS = (0.5, 1, 2, 4, 8)
SEEDS = (42, 43, 44)

_CONFIG_HEADER = """# GENERATED by scripts/grid_holes.py -- do not hand-edit.
#
# Backfill for cells that were dispatched but produced no meta.json. Each
# wanted cell is one value of the `cell` axis, split back into
# placement/epsilon/seed by expand_cell() in the pre-trial hook, because
# `method: grid` can only enumerate a cross-product and these holes are
# scattered.
name: {name}
method: grid
metric:
  name: val/auc_best
  goal: maximize
parameters:
  cell:
    values:
"""

_CONFIG_TAIL = """  processed-dir:
    value: {processed_dir}
  num-server-rounds:
    value: {rounds}
  embedding-dim:
    value: {dim}
  batch-sample-rate:
    value: 0.05
  combined-target-epsilon:
    value: 1000.0
"""


def landed_run_ids(meta_dir: str = "experiments/checkpoints") -> set[str]:
    """Run ids that wrote a meta.json, the only proof a trial finished."""
    return {
        os.path.basename(os.path.dirname(p))
        for p in glob.glob(f"{meta_dir}/*/meta.json")
    }


def _load_env(path: str = ".env") -> None:
    """Read WANDB_* out of .env without adding a dotenv dependency."""
    if not os.path.exists(path):
        return
    for line in open(path):
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, val = line.split("=", 1)
            os.environ.setdefault(key, val.strip().strip('"').strip("'"))


def completed_cells(sweep_ids: list[str], entity: str, project: str) -> set[tuple]:
    """(placement, epsilon, seed) for every run in these sweeps that landed."""
    import wandb

    api = wandb.Api()
    landed = landed_run_ids()
    done: set[tuple] = set()
    for sid in sweep_ids:
        for run in api.sweep(f"{entity}/{project}/{sid}").runs:
            if run.id not in landed:
                continue
            cfg = run.config
            # A backfill run carries `cell`; the original grid carried the axes.
            if "cell" in cfg and "placement" not in cfg:
                place, eps, seed = str(cfg["cell"]).split("|")
                done.add((place, float(eps), int(seed)))
            elif cfg.get("placement") is not None:
                done.add(
                    (cfg["placement"], float(cfg["epsilon"]), int(cfg["seed"]))
                )
    return done


def holes(done: set[tuple]) -> list[str]:
    """Cell strings for every intended cell with no result, in grid order."""
    return [
        f"{p}|{e:g}|{s}"
        for p in PLACEMENTS
        for e in EPSILONS
        for s in SEEDS
        if (p, float(e), s) not in done
    ]


def write_config(cells: list[str], path: str, **fmt: str | int) -> None:
    """Emit a one-axis backfill sweep covering exactly ``cells``."""
    opts = {
        "name": fmt.get("name", "icc200-placement-backfill"),
        "processed_dir": fmt.get("processed_dir", "data/processed/dedup_first"),
        "rounds": fmt.get("rounds", 200),
        "dim": fmt.get("dim", 32),
    }
    body = "".join(f'      - "{c}"\n' for c in cells)
    Path(path).write_text(
        _CONFIG_HEADER.format(name=opts["name"])
        + body
        + _CONFIG_TAIL.format(
            processed_dir=opts["processed_dir"], rounds=opts["rounds"], dim=opts["dim"]
        )
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--sweeps", nargs="+", required=True, help="Sweep ids to credit.")
    ap.add_argument("--out", default=None, help="Write a backfill config here.")
    ap.add_argument("--name", default="icc200-placement-backfill")
    ap.add_argument("--entity", default=None)
    ap.add_argument("--project", default=None)
    args = ap.parse_args()

    _load_env()
    entity = args.entity or os.environ.get("WANDB_ENTITY", "lip-etown-research")
    project = args.project or os.environ.get("WANDB_PROJECT", "JayQueryICC")

    done = completed_cells(args.sweeps, entity, project)
    missing = holes(done)
    total = len(PLACEMENTS) * len(EPSILONS) * len(SEEDS)
    print(f"landed {len(done)}/{total} cells; {len(missing)} holes")
    for cell in missing:
        print(f"  {cell}")
    if args.out and missing:
        write_config(missing, args.out, name=args.name)
        print(f"wrote {args.out} ({len(missing)} cells)")
    elif args.out:
        print("no holes; no config written")
    # Non-zero exit when holes remain, so a driver can branch on it.
    raise SystemExit(1 if missing else 0)


if __name__ == "__main__":
    main()
